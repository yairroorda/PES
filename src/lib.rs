pub fn subbytes(mut block: Block) -> Block {
    for byte in block.items.iter_mut() {
        let index = *byte as usize;
        *byte = s_box[index];
    }

    block
}

pub fn shiftrows(mut block: Block) -> Block {
    let items = block.items;

    block.items[4] = items[5];
    block.items[5] = items[6];
    block.items[6] = items[7];
    block.items[7] = items[4];

    block.items[8] = items[10];
    block.items[9] = items[11];
    block.items[10] = items[8];
    block.items[11] = items[9];

    block.items[12] = items[15];
    block.items[13] = items[12];
    block.items[14] = items[13];
    block.items[15] = items[14];

    block
}

pub fn add_round_key(mut block: Block, round_key: &PES_128) -> Block {
    for i in 0..16 {
        block.items[i] ^= round_key.key[i];
    }

    block
}

